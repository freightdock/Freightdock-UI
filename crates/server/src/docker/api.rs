//! `/api/envs/{env}/...`: Docker as Freightdock's UI uses it, environment by environment. Reads need a session; changes
//! need an administrator until roles come (M4); every change is in the activity log.

use axum::Router;
use axum::extract::DefaultBodyLimit;
use axum::routing::{get, post, put};

use super::{containers, images, networks, streams, summary, system, volume_files, volumes};
use crate::state::App;

pub fn router() -> Router<App> {
    let e = |p: &str| format!("/api/envs/{{env}}{p}");
    Router::new()
        .route(&e("/info"), get(system::info))
        .route(&e("/df"), get(system::df))
        .route(&e("/summary"), get(summary::summary))
        .route(&e("/prune"), post(system::prune))
        .route(&e("/events/ws"), get(streams::events_ws))
        .route(&e("/stats"), get(streams::all_stats))
        .route(&e("/containers"), get(containers::list).post(containers::create))
        .route(&e("/containers/prune"), post(containers::prune))
        .route(&e("/containers/{id}"), get(containers::inspect).delete(containers::remove))
        .route(&e("/containers/{id}/config"), get(containers::config))
        .route(&e("/containers/{id}/top"), get(containers::top))
        .route(&e("/containers/{id}/rename"), post(containers::rename))
        .route(&e("/containers/{id}/recreate"), post(containers::recreate))
        .route(&e("/containers/{id}/access"), axum::routing::put(containers::set_access))
        .route(&e("/containers/{id}/logs"), get(streams::logs_download))
        .route(&e("/containers/{id}/logs/ws"), get(streams::logs_ws))
        .route(&e("/containers/{id}/stats"), get(streams::stats_one))
        .route(&e("/containers/{id}/stats/ws"), get(streams::stats_ws))
        .route(&e("/containers/{id}/exec"), post(streams::exec_run))
        .route(&e("/containers/{id}/exec/ws"), get(streams::exec_ws))
        .route(&e("/containers/{id}/attach/ws"), get(streams::attach_ws))
        .route(&e("/containers/{id}/{action}"), post(containers::action))
        .route(&e("/images"), get(images::list))
        .route(&e("/images/prune"), post(images::prune))
        .route(&e("/images/pull"), post(images::pull))
        .route(&e("/images/push"), post(images::push))
        .route(&e("/images/build"), post(images::build).layer(DefaultBodyLimit::disable()))
        .route(&e("/images/load"), post(images::load).layer(DefaultBodyLimit::disable()))
        .route(&e("/images/{id}"), get(images::inspect).delete(images::remove))
        .route(&e("/images/{id}/tag"), post(images::tag))
        .route(&e("/images/{id}/access"), put(images::set_access))
        .route(&e("/images/{id}/export"), get(images::export))
        .route(&e("/volumes"), get(volumes::list).post(volumes::create))
        .route(&e("/volumes/prune"), post(volumes::prune))
        .route(&e("/volumes/{name}"), get(volumes::inspect).delete(volumes::remove))
        .route(&e("/volumes/{name}/access"), put(volumes::set_access))
        .route(&e("/volumes/{name}/files"), get(volume_files::list).delete(volume_files::delete))
        .route(&e("/volumes/{name}/files/download"), get(volume_files::download))
        .route(&e("/volumes/{name}/files/upload"), post(volume_files::upload).layer(DefaultBodyLimit::max(volume_files::UPLOAD_MAX + (1 << 20))))
        .route(&e("/volumes/{name}/files/mkdir"), post(volume_files::mkdir))
        .route(&e("/networks"), get(networks::list).post(networks::create))
        .route(&e("/networks/prune"), post(networks::prune))
        .route(&e("/networks/{id}"), get(networks::inspect).delete(networks::remove))
        .route(&e("/networks/{id}/access"), put(networks::set_access))
        .route(&e("/networks/{id}/connect"), post(networks::connect))
        .route(&e("/networks/{id}/disconnect"), post(networks::disconnect))
        .route(&e("/templates/deploy"), post(crate::templates::deploy))
        .route(&e("/stacks"), get(crate::stacks::list).post(crate::stacks::create))
        .route(&e("/stacks/adopt"), post(crate::stacks::adopt))
        .route(&e("/stacks/git"), post(crate::stacks::create_git))
        .route(&e("/webhooks"), get(crate::webhooks::list))
        .route(&e("/stacks/{id}/webhook"), post(crate::webhooks::make_stack).delete(crate::webhooks::remove_stack))
        .route(&e("/containers/{id}/webhook"), post(crate::webhooks::make_container).delete(crate::webhooks::remove_container))
        .route(&e("/stacks/{id}/git"), axum::routing::put(crate::stacks::update_git))
        .route(&e("/stacks/{id}/access"), axum::routing::put(crate::stacks::set_access))
        .route(&e("/stacks/external/{name}"), get(crate::stacks::external))
        .route(&e("/stacks/{id}"), get(crate::stacks::get).put(crate::stacks::update))
        .route(&e("/stacks/{id}/environment"), get(crate::stacks::environment))
        .route(&e("/stacks/{id}/{action}"), post(crate::stacks::act))
        .merge(super::swarm::router())
}
